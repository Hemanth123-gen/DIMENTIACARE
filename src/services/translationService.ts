export const getLocalizedActivity = (act: Activity, language: string): Activity => {
  if (act.translations && act.translations[language]) {
    return { ...act, title: act.translations[language].title || act.title };
  }
  const langKey = language || 'English';
  const translations = activityTranslations[langKey] || activityTranslations.English;
  const translatedTitle = translations[act.title] || act.title;
  return { ...act, title: translatedTitle };
};

export const getLocalizedReminder = (rem: Reminder, language: string): Reminder => {
  if (rem.translations && rem.translations[language]) {
    return {
      ...rem,
      title: rem.translations[language].title || rem.title,
      description: rem.translations[language].description || rem.description
    };
  }
  const langKey = language || 'English';
  const translations = reminderTranslations[langKey] || reminderTranslations.English;
  const translation = translations[rem.title] || translations[rem.description] || translations[rem.category] || null;
  
  if (translation) {
    return {
      ...rem,
      title: translation.title || rem.title,
      description: translation.desc || rem.description
    };
  }
  
  // Try mapping by description if title didn't match directly
  for (const key of Object.keys(translations)) {
    if (rem.description.toLowerCase().includes(key.toLowerCase()) || rem.title.toLowerCase().includes(key.toLowerCase())) {
      return {
        ...rem,
        title: translations[key].title,
        description: translations[key].desc
      };
    }
  }
  
  return rem;
};

export const getLocalizedMemory = (mem: Memory, language: string): Memory => {
  const langKey = language || 'English';
  const translations = memoryTranslations[langKey] || memoryTranslations.English;
  const translation = translations[mem.title] || null;
  
  if (translation) {
    return {
      ...mem,
      title: translation.title || mem.title,
      description: translation.desc || mem.description
    };
  }
  
  // Try mapping substring
  for (const key of Object.keys(translations)) {
    if (mem.title.toLowerCase().includes(key.toLowerCase())) {
      return {
        ...mem,
        title: translations[key].title,
        description: translations[key].desc
      };
    }
  }
  
  return mem;
};

export const generateTranslations = async (
  title: string,
  description: string
): Promise<Record<string, { title: string; description?: string }>> => {
  const fallback: Record<string, { title: string; description?: string }> = {};
  const languages: string[] = ['English', 'Hindi', 'Bengali', 'Assamese', 'Manipuri', 'Khasi', 'Mizo', 'Nagamese', 'Tripuri'];

  languages.forEach(l => {
    fallback[l] = { title, description };
  });

  try {
    if (apiClient.getStatus() === 'connected') {
      const res = await apiClient.post<any>('/voice/translate', { title, description });
      if (res && res.success && res.translations) {
        return res.translations;
      }
    }
  } catch (err) {
    console.warn('[Translation] LLM translation failed, using fallback.');
  }

  languages.forEach(lang => {
    const staticRem = reminderTranslations[lang] || {};
    for (const key of Object.keys(staticRem)) {
      if (title.toLowerCase() === key.toLowerCase()) {
        fallback[lang] = {
          title: staticRem[key].title,
          description: staticRem[key].desc
        };
        return;
      }
    }
    if (title.toLowerCase().includes('medicine') || title.toLowerCase().includes('dawai')) {
      const staticMed = staticRem['Medicine'] || { title: 'Medicine', desc: 'Take medicine' };
      fallback[lang] = { title: staticMed.title, description: staticMed.desc };
    } else if (title.toLowerCase().includes('water') || title.toLowerCase().includes('pani')) {
      const staticWater = staticRem['Drink Water'] || { title: 'Drink Water', desc: 'Drink water' };
      fallback[lang] = { title: staticWater.title, description: staticWater.desc };
    } else if (title.toLowerCase().includes('walk') || title.toLowerCase().includes('sair')) {
      const staticWalk = staticRem['Evening Walk'] || { title: 'Evening Walk', desc: 'Evening Walk' };
      fallback[lang] = { title: staticWalk.title, description: staticWalk.desc };
    } else if (title.toLowerCase().includes('call') || title.toLowerCase().includes('phone')) {
      const staticCall = staticRem['Call Anu'] || { title: 'Call Anu', desc: 'Call daughter' };
      fallback[lang] = { title: staticCall.title, description: staticCall.desc };
    }
  });

  return fallback;
};
